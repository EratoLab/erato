#!/usr/bin/env node
// Builds the web's tool call cards for Adaptive Card surfaces and writes the
// script the backend loads. `--check` fails when the committed one is stale.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const frontend = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const target = path.resolve(
  frontend,
  "../backend/erato/src/services/adaptive_cards/tool_call_cards.generated.js",
);
const check = process.argv.includes("--check");
const HEADER =
  "// Generated by frontend/scripts/build-adaptive-cards.mjs from the web's tool call cards. Do not edit.\n";

const outDir = mkdtempSync(path.join(tmpdir(), "erato-adaptive-cards-"));
try {
  execFileSync("pnpm", ["exec", "lingui", "compile"], {
    cwd: frontend,
    stdio: "inherit",
  });
  execFileSync(
    "pnpm",
    [
      "exec",
      "vite",
      "build",
      "--config",
      "vite.adaptive-cards.config.ts",
      "--logLevel",
      "warn",
    ],
    {
      cwd: frontend,
      stdio: "inherit",
      env: {
        ...process.env,
        ADAPTIVE_CARDS_OUT_DIR: outDir,
        VITE_CONFIG_NATIVE_IGNORE_WARNING: "true",
      },
    },
  );
  const built =
    HEADER + readFileSync(path.join(outDir, "tool_call_cards.js"), "utf8");
  if (check) {
    let committed = "";
    try {
      committed = readFileSync(target, "utf8");
    } catch {
      // A missing file is as stale as an old one.
    }
    if (committed !== built) {
      console.error(
        `${path.relative(process.cwd(), target)} is out of date. Run \`pnpm build:adaptive-cards\` in frontend/ and commit the result.`,
      );
      process.exit(1);
    }
    console.log("Adaptive card bundle is up to date.");
  } else {
    writeFileSync(target, built);
    console.log(
      `Wrote ${path.relative(process.cwd(), target)} (${Math.round(built.length / 1024)} KB).`,
    );
  }
} finally {
  rmSync(outDir, { recursive: true, force: true });
}
