<#
.SYNOPSIS
Checks and configures the Azure side of the Erato Teams bot. Version 1.1.1.
.DESCRIPTION
Run in Azure Cloud Shell (PowerShell), or PowerShell 7.2+ with Azure CLI.
The default run only reads Azure and Entra. -WhatIf previews changes.
-Apply shows the plan and requests confirmation before it:
creates the single-tenant Azure Bot for the existing app registration when
-ResourceGroup and -BotName name one that does not exist yet (registering the
Microsoft.BotService provider if needed), sets its messaging endpoint and Teams
channel, adds SSO settings to the existing authentication app, creates a
separate OAuth connection with a dedicated credential (or repairs the
authentication-app-ID URI generated by version 1.0.0), and grants tenant-wide
consent for the delegated Graph permissions unless -SkipConsent is set.
Existing redirects, permissions, credentials and bot identity are preserved.
Erato itself and the Teams package upload remain separate.
Public Azure and the global Bot Framework token service are supported.
Exit codes: 0 = checks/writes completed; 1 = settings missing; 2 = blocked/failed.
Source and instructions: https://erato.chat/docs/integrations/ms_teams
#>
[CmdletBinding(SupportsShouldProcess, ConfirmImpact = 'High')]
